"""Bearer identities and request-wide repository isolation.

Only local development may use the explicitly enabled demo identity. API tokens
are randomly generated by the provisioning CLI; only SHA-256 hashes are stored.
"""
import hashlib
from uuid import UUID

from fastapi import Depends, HTTPException, Request
from sqlalchemy import event, select
from sqlalchemy.orm import Session, with_loader_criteria

from app.core.config import settings
from app.db import models
from app.db.session import get_db


def demo_auth_enabled() -> bool:
    return settings.demo_mode and settings.app_env.lower() == "development"


def token_hash(token: str) -> str:
    return hashlib.sha256(token.encode("utf-8")).hexdigest()


def apply_repository_scope(db: Session, user: models.User) -> None:
    if user.role == "owner":
        return
    ids = tuple(db.scalars(select(models.RepositoryMember.repo_id).where(models.RepositoryMember.user_id == user.id)))
    db.info["repository_scope"] = ids
    db.info["identity_id"] = user.id


@event.listens_for(Session, "do_orm_execute")
def _scope_queries(state) -> None:
    ids = state.session.info.get("repository_scope")
    if ids is None or not (state.is_select or state.is_update or state.is_delete):
        return
    # Expressions rather than closure lambdas avoid stale tenant values in the
    # SQLAlchemy statement cache. Apply to lists, get(), aliases and ORM DML.
    options = [with_loader_criteria(models.Repository, models.Repository.id.in_(ids), include_aliases=True)]
    for mapper in models.Base.registry.mappers:
        cls = mapper.class_
        if hasattr(cls, "repo_id"):
            options.append(with_loader_criteria(cls, cls.repo_id.in_(ids), include_aliases=True))
    prs = select(models.PullRequest.id).where(models.PullRequest.repo_id.in_(ids))
    for cls in (models.PRFile, models.PRReviewComment):
        options.append(with_loader_criteria(cls, cls.pr_id.in_(prs), include_aliases=True))
    workflows = select(models.AgentWorkflowRun.id).where(models.AgentWorkflowRun.repo_id.in_(ids))
    options.append(with_loader_criteria(models.AgentTaskRun, models.AgentTaskRun.workflow_id.in_(workflows), include_aliases=True))
    options.append(with_loader_criteria(models.Workspace, models.Workspace.created_by == state.session.info["identity_id"], include_aliases=True))
    options.append(with_loader_criteria(models.EvalRun, models.EvalRun.result_json["target"]["repo_id"].as_string().in_([str(i) for i in ids]), include_aliases=True))
    targets = select(models.Issue.id).where(models.Issue.repo_id.in_(ids)).union(
        select(models.PullRequest.id).where(models.PullRequest.repo_id.in_(ids)),
        select(models.WorkflowRun.id).where(models.WorkflowRun.repo_id.in_(ids)),
    )
    options.append(with_loader_criteria(models.AnalysisResult, models.AnalysisResult.target_id.in_(targets), include_aliases=True))
    state.statement = state.statement.options(*options)


def current_user(request: Request, db: Session = Depends(get_db)) -> models.User:
    cached = getattr(request.state, "user", None)
    if cached is not None:
        return cached
    authorization = request.headers.get("authorization", "")
    if not authorization and demo_auth_enabled():
        from app.services.permissions import ensure_demo_user
        user = ensure_demo_user(db)
    else:
        scheme, _, token = authorization.partition(" ")
        if scheme.lower() != "bearer" or not token:
            raise HTTPException(401, "请提供访问令牌", headers={"WWW-Authenticate": "Bearer"})
        user = db.scalar(select(models.User).where(models.User.api_token_hash == token_hash(token)))
        if user is None:
            raise HTTPException(401, "访问令牌无效", headers={"WWW-Authenticate": "Bearer"})
    request.state.user = user
    db.info["actor_id"] = user.id
    apply_repository_scope(db, user)
    return user


async def authorize_api(request: Request, user: models.User = Depends(current_user), db: Session = Depends(get_db)) -> None:
    from app.services.permissions import has_permission
    path = request.scope["path"]
    permission = "repo:read"
    if request.method not in {"GET", "HEAD", "OPTIONS"}:
        permission = "agent:run"
        if request.method == "DELETE" or path.endswith(("/connect", "/config")) or path == "/api/workspaces":
            permission = "settings:manage"
        elif path.endswith("/sync"):
            permission = "repo:sync"
        elif path.startswith("/api/action-drafts"):
            permission = "draft:approve" if path.endswith("/confirm") else "draft:create"
    if not has_permission(user, permission):
        raise HTTPException(403, f"需要权限：{permission}")
    # Validate every explicitly supplied repo id before services can create new
    # rows or start privileged background work outside this request session.
    values = dict(request.query_params)
    values.update(request.path_params)
    if request.headers.get("content-type", "").startswith("application/json"):
        try:
            body = await request.json()
        except ValueError:
            body = None
        if isinstance(body, dict):
            values.update(body)
    repo_ids = list(values.get("repo_ids") or []) if isinstance(values.get("repo_ids"), list) else []
    if values.get("repo_id"):
        repo_ids.append(values["repo_id"])
    if user.role != "owner" and path.startswith("/api/chat") and request.method == "POST" and not repo_ids:
        raise HTTPException(403, "成员的 Agent 请求必须指定有权访问的仓库")
    for raw in repo_ids:
        try:
            repo_id = UUID(str(raw))
        except ValueError:
            raise HTTPException(422, "repo_id 无效")
        if db.get(models.Repository, repo_id) is None:
            raise HTTPException(404, "未找到仓库")
